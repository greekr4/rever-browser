// Regenerates rever/src/locales.rs from the Electron app's dictionaries, so both
// apps show the same strings. Run: bun scripts/gen-rust-locales.ts
import { en } from '../src/renderer/src/locales/en'
import { ko } from '../src/renderer/src/locales/ko'

const lit = (s: string): string => JSON.stringify(s).replace(/\$/g, '$') // JSON string escapes are valid Rust
const keys = Object.keys(en).sort()
const rows = keys.map((k) => `    (${lit(k)}, ${lit((en as Record<string, string>)[k])}, ${lit((ko as Record<string, string>)[k] ?? '')}),`)
const out = `//! Port of \`src/renderer/src/locales/en.ts\` and
//! Port of \`src/renderer/src/locales/ko.ts\`.
//! GENERATED by scripts/gen-rust-locales.ts — do not edit by hand.

/// (key, English, Korean), sorted by key. An empty Korean entry falls back to English.
pub static STRINGS: &[(&str, &str, &str)] = &[
${rows.join('\n')}
];
`
await Bun.write(new URL('../rever/src/locales.rs', import.meta.url), out)
console.log(`${keys.length} keys`)
